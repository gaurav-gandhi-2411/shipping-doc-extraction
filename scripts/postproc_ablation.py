def total_pointer_stats(ctx: Ctx, gold: dict[str, Any], pred: dict[str, Any]) -> dict[str, Any]:
    """OCR labelled-total vs the VLM total: how often the pointer exists / agrees (counts)."""
    sc = ev.load_scorer()
    c: Counter[str] = Counter()
    for d, g in gold.items():
        if g["doc_type"] != "invoice":
            continue
        c["invoices"] += 1
        ocr_v = ctx.total_value[d]
        if ctx.total_page[d] is None:
            c["no_label_found"] += 1
            continue
        c["label_found"] += 1
        multipage = len(ctx.pages[d]) > 1
        c["label_on_last_page"] += ctx.total_page[d] == len(ctx.pages[d]) - 1
        c["multipage"] += multipage
        vlm_ok = sc.same(
            "total_amount", pred[d]["header"].get("total_amount"), g["header"]["total_amount"]
        )
        c["vlm_total_correct"] += vlm_ok
        if ocr_v is not None:
            agree = sc.same("total_amount", pred[d]["header"].get("total_amount"), ocr_v)
            c["ocr_value_parsed"] += 1
            c["agree"] += agree
            c["agree_and_vlm_correct"] += agree and vlm_ok
            c["disagree_and_vlm_correct"] += (not agree) and vlm_ok
    return dict(c)


