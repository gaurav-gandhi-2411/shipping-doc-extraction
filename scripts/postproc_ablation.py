def pct(x: float) -> str:
    return f"{100 * x:.2f}"


def ci_str(lo: float, hi: float) -> str:
    return f"[{100 * lo:+.2f}, {100 * hi:+.2f}]"


def kept_decision(rid: str, step: dict[str, Any]) -> str:
    """G3 gate per rung: CI of dOVERALL vs previous excludes 0, or false-fill drops with OVERALL
    not lower."""
    d = step["vs_prev"]
    if excludes_0(d["OVERALL"]):
        return (
            "KEEP (CI excludes 0)"
            if d["OVERALL"]["delta"] > 0
            else "DROP (CI excludes 0, negative)"
        )
    ff, ov = d["false_fill_rate"]["delta"], d["OVERALL"]["delta"]
    if ff < 0 and ov >= 0:
        return "KEEP (false-fill lower, OVERALL not lower)"
    return "FAIL gate (no measured effect)" if ov == 0 and ff == 0 else "FAIL gate (CI includes 0)"


