    L: list[str] = []
    rungs = res["ladder"]["rungs"]
    f1 = lambda x: "n/a" if x is None else f"{100 * x:.1f}%"  # noqa: E731
    L.append(f"## {SECTION_500}")
    L.append("")
    L.append(
        f"**Every number below is UNVERIFIED** (the verifier recomputes them). Provenance: run `{meta['run']}`, manifest code_sha "
        f"`{meta['code_sha']}`, trace git_commit `{meta['code']}`, repo HEAD `{meta['head']}`, command `{meta['command']}`. "
        f"n = {meta['n_docs']} docs ({meta['n_train']} train + {meta['n_dev']} dev), image-only keyed Qwen3.5-4B zero-shot, "
        f"decided on unseen results (spec section 5); paired document-level bootstrap, {N_BOOT} resamples, seed {SEED}, "
        "`shipdoc.eval.paired_bootstrap`; scorer unmodified. Deltas are in OVERALL points (x100)."
    )
    L.append("")
    L.append(
        "Method notes. Pages go through `shipdoc.coerce.page_for_merge` and every rung's document through `coerce_doc` + `repair_doc`, "
        "the run writer's own path. R0 is defined as in the dev100 block above. The R1b layout clusters and the R6 pointer use OCR "
        f"only; the cluster fit set ({res['clusters']['n_fit']} train+dev invoice page-1 signatures, label-free) OVERLAPS the evaluated "
        "docs: no label is used, but the cluster of a doc was fit with that doc's own layout signature, so the R1b measurement is not "
        f"held out in the layout sense. Parse failures in this run: {meta['parse_failures']} pages. "
        "Synthetic sections (R1 / R2 mechanism, injection) are not re-run; see the dev100 block."
    )
    L.append("")
    L.append("### (a) Cumulative ladder")
    L.append("")
    L.append(
        "| step | rule | OVERALL [95% CI] | false-fill rate [95% CI] | d vs previous [CI] | d vs R0 [CI] | values changed vs previous | G3 verdict | gate |"
    )
    L.append("|---|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(rungs):
        ci = f"{pct(r['OVERALL'])} [{pct(r['OVERALL_ci'][0])}, {pct(r['OVERALL_ci'][1])}]"
        ff = f"{pct(r['false_fill'])} [{pct(r['false_fill_ci'][0])}, {pct(r['false_fill_ci'][1])}]"
        if i == 0:
            L.append(f"| R0 | {r['label']} | {ci} | {ff} | - | - | - | - | - |")
            continue
        p, z = r["vs_prev"]["OVERALL"], r["vs_R0"]["OVERALL"]
        chs = ", ".join(f"{k}:{v}" for k, v in sorted(r["changes_vs_prev"].items())) or "none"
        v = kept_decision(r["id"], r)
        L.append(
            f"| {r['id']} | {r['label']} | {ci} | {ff} | {100 * p['delta']:+.2f} {ci_str(p['lo'], p['hi'])} | "
            f"{100 * z['delta']:+.2f} {ci_str(z['lo'], z['hi'])} | {chs} | {v} | {gate_word(v)} |"
        )
    L.append("")
    L.append(f"Baseline consistency (R8 vs the run's own `predictions.json`): {meta['repro']}")
    L.append("")
    L.append("### (b) Leave-one-out (full pipeline minus one rule)")
    L.append("")
    L.append(
        "| rule | OVERALL without | d (full - without) [CI] | values changed | CI excludes 0 |"
    )
    L.append("|---|---|---|---|---|")
    for r in res["ladder"]["loo"]:
        d = r["full_minus_without"]["OVERALL"]
        chs = ", ".join(f"{k}:{v}" for k, v in sorted(r["changes"].items())) or "none"
        L.append(
            f"| {r['id']} {r['label']} | {pct(r['OVERALL_without'])} | {100 * d['delta']:+.2f} {ci_str(d['lo'], d['hi'])} | {chs} | {'yes' if excludes_0(d) else 'no'} |"
        )
    L.append("")
    L.append(
        "### (c) Per-field effects (docs whose field went wrong->right / right->wrong, vs previous rung)"
    )
    L.append("")
    L.append("| step | header fields | row effect (correct rows / predicted rows) |")
    L.append("|---|---|---|")
    for r in rungs[1:]:
        fl = (
            ", ".join(
                f"{k}: +{v['gain']}/-{v['loss']}"
                for k, v in sorted(r["header_flips_vs_prev"].items())
            )
            or "no field changed"
        )
        re_ = r["row_effect_vs_prev"]
        L.append(f"| {r['id']} | {fl} | {re_['rows_full']:+d} / {re_['rows_pred']:+d} |")
    L.append("")
    r0, rf = rungs[0], rungs[-1]
    L.append("Header accuracy by field, R0 -> R8:")
    L.append("")
    L.append("| field | R0 | R8 |")
    L.append("|---|---|---|")
