def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--run-dir", type=Path, default=paths.runs_dir() / DEFAULT_RUN)
    ap.add_argument(
        "--out-dir", type=Path, default=paths.runs_dir() / "diagnosis" / "postproc_ablation"
    )
    ap.add_argument("--labels", type=Path, default=None, help="default: <data>/dev/labels")
    ap.add_argument("--write-report", action="store_true")
    ap.add_argument(
        "--docs",
        choices=("dev", "train+dev"),
        default="dev",
        help="dev: the dev100 run (default); train+dev: a 500-doc run, own report block",
    )
    ap.add_argument(
        "--report-tag",
        default="",
        help="train+dev with --write-report: write a separate tagged block (e.g. 'native "
        "resolution') instead of replacing the default 500-doc block",
    )
    args = ap.parse_args(argv)
    full_mode = args.docs == "train+dev"

    traces = read_trace(args.run_dir / "trace.jsonl")
    corp = load_corpus()
    recs: dict[str, Any] = {}
    if full_mode:
        recs = select_docs(corp, [t["doc_id"] for t in traces])
        gold = {d: r.gold for d, r in recs.items()}
    else:
        gold = ev.load_gold(args.labels or paths.data_dir() / "dev" / "labels")
        gold = {d: gold[d] for d in (t["doc_id"] for t in traces)}
    saved = json.loads((args.run_dir / "predictions.json").read_text(encoding="utf-8"))

    # Label-free layout clusters: fit on train+dev invoice page-1 OCR (never test).
    inv = [r for r in corp if r.doc_type == "invoice"]
    sig = {r.doc_id: layout_signature(r.pages()[0]) for r in inv}
    clusters = LayoutClusters.fit([sig[r.doc_id] for r in inv])
    cl_ids = dict(
        zip((r.doc_id for r in inv), clusters.predict([sig[r.doc_id] for r in inv]), strict=True)
    )
    from sklearn.metrics import adjusted_rand_score

    ari = float(adjusted_rand_score([r.group for r in inv], [cl_ids[r.doc_id] for r in inv]))
    by_c: dict[int, Counter[str]] = defaultdict(Counter)
    for r in inv:
        by_c[cl_ids[r.doc_id]][r.group] += 1
    purity = sum(max(c.values()) for c in by_c.values()) / len(inv)

    ctx = Ctx(traces, finalize=full_mode)
    raw = raw_dates(ctx)
    pools: dict[int, list[str]] = defaultdict(list)
    for d, v in raw.items():
        if v and d in cl_ids:
            pools[cl_ids[d]].append(v)
    orders = {c: infer_date_order(v) for c, v in pools.items()}
    ctx.date_order = {d: orders.get(cl_ids.get(d, -1)) for d in raw}

    lad = ladder(ctx, gold)
    full = lad["preds"]["R8"]
    if full_mode:
        cl_stats = {
            "k": clusters.k,
            "silhouette": clusters.silhouette,
            "n_fit": len(inv),
            "ari": ari,
            "purity": purity,
        }
        return finish_500(args, traces, ctx, lad, saved, gold, recs, raw, corp, cl_stats)
    # Reproduction check: R8 without R6/R1b is exactly the shipped merge+normalize default.
    default_equiv = run_all(replace(FULL, total_ocr=False, cluster_dates=False), ctx)
    repro = (
        "R8 minus R6/R1b == saved predictions.json: "
        + str(default_equiv == saved)
        + f"; R8 == saved: {full == saved}"
    )
    # R3 / R4 cannot move a score: predictions are unchanged by construction; re-score to show it.
    assert (
        ev.score(full, gold)["all"]["OVERALL"]
        == ev.score(json.loads(json.dumps(full)), gold)["all"]["OVERALL"]
    )
    corpus_gold = [r.gold for r in corp]
    res = {
        "ladder": {k: v for k, v in lad.items() if k != "preds"},
        "validators": validator_report(full, gold, corpus_gold),
        "injection": validator_injection(corpus_gold),
        "clusters": {
            "k": clusters.k,
            "silhouette": clusters.silhouette,
            "n_fit": len(inv),
            "ari": ari,
            "purity": purity,
        },
        "date_synthetic": date_synthetic(corp, cl_ids),
        "number_synthetic": number_synthetic(gold),
        "total_pointer": total_pointer_stats(ctx, gold, full),
        "merge_events": merge_events(ctx, gold),
        "no_invention": no_invention(lad["preds"]["R0"], full),
    }
    date_vals = [v for v in raw.values() if v]
    meta = {
        "run": str(args.run_dir.relative_to(paths.runs_dir()))
        if args.run_dir.is_relative_to(paths.runs_dir())
        else args.run_dir.name,
        "code": traces[0].get("git_commit", "?"),
        "n_docs": len(gold),
        "parse_failures": sum(p is None for pages in ctx.pages.values() for p in pages),
        "repro": repro,
        "date_iso": sum(bool(re.fullmatch(r"\d{4}-\d{2}-\d{2}", v)) for v in date_vals),
        "date_total": len(date_vals),
    }
    meta["decision_lines"] = decision_lines(res)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "postproc_ablation.json").write_text(
        json.dumps({"meta": meta, **res}, indent=1, default=str), encoding="utf-8"
    )
    md = build_markdown(res, meta)
    (args.out_dir / "postproc_ablation.md").write_text(md, encoding="utf-8")
    if args.write_report:
        write_report(md)
    print(md)
    return 0


