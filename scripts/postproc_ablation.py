# ------------------------------------------------------------------------------ pipeline


class Ctx:
    """Everything a rung needs besides its Rules: parsed pages, OCR totals, cluster date orders."""

    def __init__(self, traces: list[dict[str, Any]], finalize: bool = False) -> None:
        self.prov = FieldProvenance.load()
        # finalize = the run writer's path: number token text kept through the merge, and every
        # output coerced to plain-number strings + schema-invalid dates nulled (shipdoc.coerce).
        self.finalize = finalize
        self.pages = {t["doc_id"]: [self._page(p["raw_text"]) for p in t["pages"]] for t in traces}
        self.date_order: dict[str, str | None] = {}  # set once the layout clusters are fit
        self.total_page: dict[str, int | None] = {}
        self.total_value: dict[str, str | None] = {}
        for t in traces:
            cand = pick_total(ocr.doc_pages(t["doc_id"]))
            self.total_page[t["doc_id"]] = None if cand is None else cand.page
            self.total_value[t["doc_id"]] = None if cand is None else cand.value

    def _page(self, raw: str) -> dict[str, Any] | None:
        """One page as the merge receives it (token-text numbers when finalizing)."""
        parsed = parse_output(raw, "json")
        return page_for_merge(raw, parsed, "json") if self.finalize else parsed


def run_doc(doc_id: str, rules: Rules, ctx: Ctx) -> tuple[dict[str, Any], dict[str, list[str]]]:
    """parse -> merge -> normalize of one doc under `rules`; returns (doc, normalize flags)."""
    page = ctx.total_page[doc_id] if rules.total_ocr else None
    hints = {"total_amount": page} if page is not None else None
    merged = merge_pages(
        ctx.pages[doc_id],
        ctx.prov,
        drop_null_rows=rules.null_rows,
        provenance_aware=rules.provenance,
        drop_header_rows=rules.header_rows,
        total_page_hints=hints,
    )
    order = ctx.date_order.get(doc_id) if rules.cluster_dates else None
    doc, flags = normalize_doc(
        merged.doc,
        dates=rules.dates,
        numbers=rules.numbers,
        codes=rules.codes,
        date_order=order,
    )
    if ctx.finalize:
        doc = repair_doc(coerce_doc(doc))[0]
    return doc, flags


def run_all(rules: Rules, ctx: Ctx) -> dict[str, Any]:
    """Predictions of every doc under `rules`."""
    return {d: run_doc(d, rules, ctx)[0] for d in ctx.pages}


def raw_dates(ctx: Ctx) -> dict[str, str | None]:
    """Merged raw ``invoice_date`` per doc (before normalisation), the input of R1."""
    out: dict[str, str | None] = {}
    for d, pages in ctx.pages.items():
        v = merge_pages(pages, ctx.prov).doc["header"].get("invoice_date")
        out[d] = None if v is None else str(v).strip() or None
    return out


# ------------------------------------------------------------------------------ statistics


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson 95% interval of a proportion (0/0 -> (nan, nan))."""
    if n == 0:
        return math.nan, math.nan
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def paired(pa: dict[str, Any], pb: dict[str, Any], gold: dict[str, Any]) -> dict[str, Any]:
    """Paired bootstrap of B - A on OVERALL (+ false-fill). Identical predictions: exact zeros
    (every resample gives the same score for both systems, so the percentile CI is [0, 0])."""
    if pa == pb:
        z = {"delta": 0.0, "lo": 0.0, "hi": 0.0}
        return {"OVERALL": z, "false_fill_rate": dict(z), "identical": True}
    r = ev.paired_bootstrap(pa, pb, gold, n=N_BOOT, seed=SEED)
    keep = ("delta", "lo", "hi")
    return {
        "OVERALL": {k: r["OVERALL"][k] for k in keep},
        "false_fill_rate": {k: r["false_fill_rate"][k] for k in keep},
        "identical": False,
    }


def excludes_0(d: dict[str, float]) -> bool:
    return d["lo"] > 0 or d["hi"] < 0


def cell_changes(pa: dict[str, Any], pb: dict[str, Any]) -> dict[str, int]:
    """Cells that differ between two prediction sets: ``header.<f>`` counts and ``rows`` /
    ``row_cells`` (rows added/removed, row fields edited). Counts only."""
    c: Counter[str] = Counter()
    for d, a in pa.items():
        b = pb[d]
        for k in set(a["header"]) | set(b["header"]):
            if a["header"].get(k) != b["header"].get(k):
                c[f"header.{k}"] += 1
        c["rows"] += abs(len(a["line_items"]) - len(b["line_items"]))
        if len(a["line_items"]) == len(b["line_items"]):
            for ra, rb in zip(a["line_items"], b["line_items"], strict=True):
                c["row_cells"] += sum(ra.get(k) != rb.get(k) for k in set(ra) | set(rb))
    return {k: v for k, v in c.items() if v}


def header_flips(
    pa: dict[str, Any], pb: dict[str, Any], gold: dict[str, Any]
) -> dict[str, dict[str, int]]:
    """Per header field: docs that went wrong->right (``gain``) and right->wrong (``loss``)."""
    ra, rb = ev.per_doc_results(pa, gold), ev.per_doc_results(pb, gold)
    out: dict[str, dict[str, int]] = defaultdict(lambda: {"gain": 0, "loss": 0})
    for d in gold:
        for k, ok_a in ra[d]["header"].items():
            ok_b = rb[d]["header"][k]
            if ok_b and not ok_a:
                out[k]["gain"] += 1
            elif ok_a and not ok_b:
                out[k]["loss"] += 1
    return dict(out)


def row_effect(pa: dict[str, Any], pb: dict[str, Any], gold: dict[str, Any]) -> dict[str, int]:
    """Change in correct rows / predicted rows (totals over the docs)."""
    ra, rb = ev.per_doc_results(pa, gold), ev.per_doc_results(pb, gold)
    return {
        "rows_full": sum(rb[d]["rows_full"] - ra[d]["rows_full"] for d in gold),
        "rows_pred": sum(rb[d]["rows_pred"] - ra[d]["rows_pred"] for d in gold),
    }


def point(pred: dict[str, Any], gold: dict[str, Any]) -> dict[str, Any]:
    """Aggregate metrics + 95% CIs of OVERALL / false-fill of one prediction set."""
    agg = ev.score(pred, gold)["all"]
    per = list(ev.per_doc_results(pred, gold).values())
    ci = ev.bootstrap_metrics(per, n=N_BOOT, seed=SEED)
    return {
        "OVERALL": agg["OVERALL"],
        "OVERALL_ci": [ci["OVERALL"]["lo"], ci["OVERALL"]["hi"]],
        "header": agg["header_field_accuracy"],
        "row_f1": agg["row_f1"],
        "fully_correct": agg["documents_fully_correct"],
        "false_fill": agg["false_fill_rate"],
        "false_fill_ci": [ci["false_fill_rate"]["lo"], ci["false_fill_rate"]["hi"]],
        "header_by_field": agg["header_by_field"],
    }


# ------------------------------------------------------------------------------ ladder


def ladder(ctx: Ctx, gold: dict[str, Any]) -> dict[str, Any]:
    """Cumulative ladder, leave-one-out and per-field effects."""
    preds: dict[str, dict[str, Any]] = {}
    rules = Rules()
    preds["R0"] = run_all(rules, ctx)
    rungs = [{"id": "R0", "label": "baseline G2 (everything off)", "rules": rules}]
    for rid, label, fld in STEPS:
        rules = replace(rules, **{fld: True})
        preds[rid] = run_all(rules, ctx)
        rungs.append({"id": rid, "label": label, "rules": rules})
    out_rungs: list[dict[str, Any]] = []
    for i, r in enumerate(rungs):
        rid = r["id"]
        row: dict[str, Any] = {"id": rid, "label": r["label"], **point(preds[rid], gold)}
        if i:
            prev = rungs[i - 1]["id"]
            row["vs_prev"] = paired(preds[prev], preds[rid], gold)
            row["vs_R0"] = paired(preds["R0"], preds[rid], gold)
            row["changes_vs_prev"] = cell_changes(preds[prev], preds[rid])
            row["header_flips_vs_prev"] = header_flips(preds[prev], preds[rid], gold)
            row["row_effect_vs_prev"] = row_effect(preds[prev], preds[rid], gold)
        out_rungs.append(row)
    loo = []
    full_pred = preds["R8"]
    for rid, label, fld in STEPS:
        pred = run_all(replace(FULL, **{fld: False}), ctx)
        loo.append(
            {
                "id": rid,
                "label": label,
                "OVERALL_without": ev.score(pred, gold)["all"]["OVERALL"],
                "full_minus_without": paired(pred, full_pred, gold),
                "changes": cell_changes(pred, full_pred),
                "header_flips": header_flips(pred, full_pred, gold),
            }
        )
    return {"rungs": out_rungs, "loo": loo, "preds": preds}


