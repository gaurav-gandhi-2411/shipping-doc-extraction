    L.append("")
    L.append("### (e) Confidence-only rules R3 / R4 (predictions of the R8 rung)")
    L.append("")
    L.append(
        "Criterion for KEEP as a confidence feature: on real errors, n_wrong >= 5, recall of errors >= 50% and flag precision >= 2x the "
        "base error rate; with fewer than 5 real errors the flag is NOT ASSESSABLE on real data. Flags cannot change a value (asserted)."
    )
    L.append("")
    L.append(
        "| flag | values | wrong | base error rate | flagged | flagged & wrong | recall of errors | flag precision | false-alarm rate (flagged / correct) [Wilson 95%] | n_wrong >= 5 criterion |"
    )
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for g, v in res["validators"].items():
        if g == "gold_false_alarms_train_dev":
            continue
        lo, hi = v["false_alarm_wilson"]
        L.append(
            f"| {g} | {v['n']} | {v['wrong']} | {f1(v['base_error_rate'])} | {v['flagged']} | {v['flagged_wrong']} | {f1(v['recall_of_errors'])} | {f1(v['flag_precision'])} | "
            f"{v['flagged_right']}/{v['n'] - v['wrong']} = {f1(v['false_alarm_rate'])} [{100 * lo:.1f}, {100 * hi:.1f}] | {validator_criterion(v)} |"
        )
    L.append("")
    L.append("False alarms on the GOLD values of all 500 train+dev docs:")
    L.append("")
    L.append("| flag | gold values | flagged | false-alarm rate |")
    L.append("|---|---|---|---|")
    for g, v in res["validators"]["gold_false_alarms_train_dev"].items():
        L.append(f"| {g} | {v['n']} | {v['flagged']} | {100 * v['flagged'] / v['n']:.2f}% |")
