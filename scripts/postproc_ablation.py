"""G3: incremental ablation of the deterministic Phase 3 rules on saved model outputs (no model).

Input: the saved trace.jsonl of a run (raw model text per page). Every rung re-runs
parse -> merge -> normalize from ``raw_text`` with a set of rules switched on, scores the 100 dev
docs with the official scorer (unmodified, via `shipdoc.eval`) and compares rungs with the repo's
paired document-level bootstrap (`shipdoc.eval.paired_bootstrap`: 2000 resamples, seed 42).

R0 (the baseline G2) switches EVERYTHING below off, precisely:
  * merge: ``provenance_aware=False`` -> doc_type of the first parsed page, every header field =
    the first non-null value over the pages in page order ("any page"), no OCR total pointer;
    rows concatenated in page order; repeated column-header rows KEPT; all-null rows KEPT;
  * normalize: dates / numbers / codes switched off (values are only stripped and str()-ed, which
    the scorer ignores);
  * schema assembly is NOT a rule and stays on in every rung: only the 4 row keys are kept and a
    waybill has no line_items (schema), pages that failed to parse count as None.

Rungs, cumulative (each adds one rule to the previous): R1a dates (per-document resolution),
R1b + per-layout-cluster day/month order, R2 numbers, R2b code normalisation (currency upper-case,
airport city stripped), R5 provenance-aware merge, R6 OCR labelled-total page pointer, R7 repeated
header-row filter, R8 all-null-row drop. R3 (ISO 4217 / IATA) and R4 (AWB shape) are confidence-only
validators: they return flags and cannot change a value, so their OVERALL delta is 0 by
construction (asserted here and in tests/test_validate.py); they are reported by what their flags
catch. Synthetic sections are labelled SYNTHETIC and never mixed into the dev100 numbers.

Run: uv run python scripts/postproc_ablation.py [--run-dir DIR] [--out-dir DIR] [--write-report]
``--docs train+dev`` re-gates on a 500-doc run (the zero-shot run, unseen by construction): the
pages go through ``shipdoc.coerce.page_for_merge`` and every rung's output through
``coerce_doc`` + ``repair_doc`` exactly like the run's own writer, so R8 minus R6/R1b can be
compared with the run's ``predictions.json``; the section "G3 re-gate - Phase 3 post-processing
(500-doc zero-shot, train+dev)" goes between its own ``G3-500`` markers and the dev100 block is
never touched.
Writes <out-dir>/postproc_ablation.json (aggregates + value-level diffs) and, with
``--write-report``, the section "G3 - Phase 3 post-processing (dev100, final pick)" of
reports/ablations.md. All numbers are UNVERIFIED until a verifier recomputes them.
"""

