def render_date(iso: str, fmt: str) -> str:
    """Gold ISO date printed in `fmt` (synthetic raw variant)."""
    y, m, d = (int(x) for x in iso.split("-"))
    return {
        "iso": iso,
        "dmy/": f"{d:02d}/{m:02d}/{y}",
        "mdy/": f"{m:02d}/{d:02d}/{y}",
        "D-MON-Y": f"{d:02d}-{_MON[m - 1].upper()}-{y}",
        "Month D, Y": f"{_MONTH[m - 1]} {d}, {y}",
    }[fmt]


def date_synthetic(corp: list[Any], cluster_of: dict[str, int]) -> dict[str, Any]:
    """SYNTHETIC: gold dates re-printed in raw formats, normalised per document vs per cluster.

    Scenario `seen_formats`: each group prints its own recon format. Scenario `numeric_stress`:
    every group prints a numeric date (groups alternate DD/MM and MM/DD), so day<=12 dates (22.7%
    of all gold dates) are genuinely ambiguous per document. Cluster pools use the predicted
    (label-free) clusters and, for comparison, the oracle supplier group. Reports counts of
    correct / unresolved (left raw, flagged) / wrong (a different ISO date).
    """
    invs = [r for r in corp if r.doc_type == "invoice" and r.gold["header"].get("invoice_date")]
    groups = sorted({r.group for r in invs})
    numeric_fmt = {g: ("dmy/" if i % 2 else "mdy/") for i, g in enumerate(groups)}
    out: dict[str, Any] = {"n_dates": len(invs)}
    for scen in ("seen_formats", "numeric_stress"):
        fmt_of = {
            r.doc_id: (
                GROUP_DATE_FORMAT[r.group] if scen == "seen_formats" else numeric_fmt[r.group]
            )
            for r in invs
        }
        raw = {
            r.doc_id: render_date(r.gold["header"]["invoice_date"], fmt_of[r.doc_id]) for r in invs
        }
        res: dict[str, Any] = {}
        for mode in ("raw_untouched", "per_document", "predicted_cluster", "oracle_group"):
            pools: dict[Any, list[str]] = defaultdict(list)
            for r in invs:
                key = cluster_of[r.doc_id] if mode == "predicted_cluster" else r.group
                pools[key].append(raw[r.doc_id])
            orders = {k: infer_date_order(v) for k, v in pools.items()}
            c = Counter()
            for r in invs:
                gold_iso = r.gold["header"]["invoice_date"]
                if mode == "raw_untouched":
                    got = raw[r.doc_id]
                else:
                    key = cluster_of[r.doc_id] if mode == "predicted_cluster" else r.group
                    order = orders[key] if mode != "per_document" else None
                    got, _ = normalize_date(raw[r.doc_id], order)
                c[
                    "correct"
                    if got == gold_iso
                    else "unresolved"
                    if got == raw[r.doc_id]
                    else "wrong"
                ] += 1
            res[mode] = dict(c)
            if mode != "per_document":
                res[mode]["pools_with_inferred_order"] = sum(o is not None for o in orders.values())
                res[mode]["pools"] = len(orders)
        out[scen] = res
    return out


def number_synthetic(gold: dict[str, Any]) -> dict[str, Any]:
    """SYNTHETIC: gold totals (2 decimals) and the first 3 quantities per doc (integers)
    re-printed with separators / symbols, scored by the official `same` untouched and after
    `normalize_number`. ``digits_altered`` counts outputs whose digit sequence differs from the
    printed one (must be 0: the normaliser may only re-format). Counts only."""
    sc = ev.load_scorer()

    def variants(x: float, two_dp: bool) -> dict[str, str]:
        s = f"{x:,.2f}" if two_dp else f"{x:,.0f}"
        eu = s.replace(",", "_").replace(".", ",").replace("_", ".")
        return {
            "comma_thousands": s,
            "code_prefix": f"USD {s}",
            "symbol_prefix": f"${s}",
            "decimal_comma": eu,
            "space_thousands": s.replace(",", " ").replace(".", ",")
            if two_dp
            else s.replace(",", " "),
            "decimal_comma_code_suffix": f"{eu} EUR",
        }

    items: list[tuple[str, str, bool]] = []
    for g in gold.values():
        if g["doc_type"] == "invoice" and g["header"].get("total_amount") is not None:
            items.append(("total_amount", str(g["header"]["total_amount"]), True))
        for r in g["line_items"][:3]:
            if r.get("quantity") is not None:
                items.append(("quantity", str(r["quantity"]), False))
    res: dict[str, Counter[str]] = defaultdict(Counter)
    for f, gv, two_dp in items:
        for name, s in variants(float(gv), two_dp).items():
            norm, _ = normalize_number(s)
            c = res[f"{f} / {name}"]
            c["n"] += 1
            c["raw_correct"] += sc.same(f, s, gv)
            c["normalized_correct"] += sc.same(f, norm, gv)
            c["digits_altered"] += re.sub(r"\D", "", norm) != re.sub(r"\D", "", s)
    return {k: dict(v) for k, v in sorted(res.items())}


