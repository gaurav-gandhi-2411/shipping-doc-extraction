def merge_events(ctx: Ctx, gold: dict[str, Any]) -> dict[str, int]:
    """How often the merge situations the rules target occur in this run (docs)."""
    c: Counter[str] = Counter()
    for d in gold:
        pages = ctx.pages[d]
        m = merge_pages(pages, ctx.prov).diffs
        c["ignored_elsewhere_docs"] += bool(m["ignored_elsewhere"])
        c["disagree_docs"] += bool(m["disagreement"])
        c["docs_with_header_rows"] += bool(m["dropped_header_rows"])
        c["docs_with_null_rows"] += bool(m["dropped_null_rows"])
        c["waybill_docs_with_rows"] += bool(m["dropped_waybill_rows"])
        c["doc_type_disagree_docs"] += len(m["doc_type_votes"]) > 1
        c["multipage_docs"] += len(pages) > 1
    return dict(c)


def no_invention(pa: dict[str, Any], pb: dict[str, Any]) -> dict[str, int]:
    """Every cell changed between two prediction sets must be a re-formatting of the old value.

    OK means: the new value is contained in the old one (airport city strip, code case), or both
    carry the same non-empty digit sequence (number separators / symbols), or - for a date - the
    new value is a valid ISO date whose year digits occur in the old value.
    """
    changed = bad = 0

    def digits(x: str) -> str:
        return re.sub(r"\D", "", x)

    def check(field: str, old: Any, new: Any) -> None:
        nonlocal changed, bad
        if old == new:
            return
        changed += 1
        o, n = str(old), str(new)
        ok = n.upper() in o.upper() or (digits(o) != "" and digits(o) == digits(n))
        if field == "invoice_date":
            ok = ok or (re.fullmatch(r"\d{4}-\d{2}-\d{2}", n) is not None and n[:4] in o)
        bad += not ok

    for d, a in pa.items():
        b = pb[d]
        for k in a["header"]:
            check(k, a["header"][k], b["header"].get(k))
        for ra, rb in zip(a["line_items"], b["line_items"], strict=False):
            for k in ra:
                check(k, ra[k], rb.get(k))
    return {"changed_cells": changed, "violations": bad}


def merge_block(text: str, md: str, begin: str = BEGIN, end: str = END) -> str:
    """`text` with the block between `begin` / `end` replaced by `md` (appended if absent). Any
    other marked block, and everything outside the markers, stays byte-identical."""
    block = f"{begin}\n{md}\n{end}\n"
    if begin in text and end in text:
        head, rest = text.split(begin, 1)
        tail = rest.split(end, 1)[1].lstrip("\n")
        return head + block + tail
    return text.rstrip("\n") + "\n\n" + block


def write_report(md: str, begin: str = BEGIN, end: str = END) -> None:
    """Create reports/ablations.md or replace only the block marked by `begin` / `end`."""
    path = ROOT / "reports" / "ablations.md"
    if path.is_file():
        text = merge_block(path.read_text(encoding="utf-8"), md, begin, end)
    else:
        text = merge_block("# Ablations and gate decisions\n", md, begin, end)
    path.write_text(text, encoding="utf-8", newline="\n")


