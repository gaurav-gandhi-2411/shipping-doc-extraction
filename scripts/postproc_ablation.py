def validator_report(
    pred: dict[str, Any], gold: dict[str, Any], corpus_gold: list[dict[str, Any]]
) -> dict[str, Any]:
    """What the confidence-only flags catch on the dev100 predictions, and their false-alarm rate
    on the gold values of all train+dev docs. Also asserts they never change a value."""
    sc = ev.load_scorer()
    before = json.dumps(pred, sort_keys=True)
    groups = {
        "R3 currency (ISO 4217)": ("currency",),
        "R3 airports (IATA)": ("origin_airport", "destination_airport"),
        "R4 AWB shape (awb_number, mawb)": ("awb_number", "mawb"),
        "R4 HAWB shape": ("hawb",),
    }
    rows: dict[str, Counter[str]] = {g: Counter() for g in groups}
    for d, g in gold.items():
        flags = validate_doc(pred[d])
        for gname, fields in groups.items():
            for f in fields:
                v = pred[d]["header"].get(f)
                if v is None or not str(v).strip():
                    continue
                wrong = not sc.same(f, v, g["header"].get(f))
                flagged = f"header.{f}" in flags
                c = rows[gname]
                c["n"] += 1
                c["wrong"] += wrong
                c["flagged"] += flagged
                c["flagged_wrong"] += flagged and wrong
                c["flagged_right"] += flagged and not wrong
    assert json.dumps(pred, sort_keys=True) == before, "validators changed a prediction"
    out: dict[str, Any] = {}
    for gname, c in rows.items():
        n, w, fl, fw = c["n"], c["wrong"], c["flagged"], c["flagged_wrong"]
        out[gname] = {
            **dict(c),
            "base_error_rate": w / n if n else None,
            "recall_of_errors": fw / w if w else None,
            "flag_precision": fw / fl if fl else None,
            "false_alarm_rate": c["flagged_right"] / (n - w) if n - w else None,
            "false_alarm_wilson": wilson(c["flagged_right"], n - w),
        }
    # False alarms on GOLD values of all 500 train+dev docs (large n; every gold value is correct).
    ga: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for g in corpus_gold:
        for f, v in g["header"].items():
            if v is None or not str(v).strip():
                continue
            fl = validate_value(f, v)
            for gname, fields in groups.items():
                if f in fields:
                    ga[gname][0] += 1
                    ga[gname][1] += bool(fl)
    out["gold_false_alarms_train_dev"] = {k: {"n": a, "flagged": b} for k, (a, b) in ga.items()}
    return out


_LOOKALIKE = {"0": "O", "1": "I", "5": "S", "8": "B", "2": "Z", "6": "G", "O": "0", "I": "1"}
_LOOKALIKE.update({"S": "5", "B": "8", "Z": "2", "G": "6"})


def _mutate(value: str, kind: str, rng: random.Random) -> str | None:
    """One synthetic reading error of `kind`; None if not applicable to this value."""
    pos = [i for i, ch in enumerate(value) if ch.isalnum()]
    if not pos:
        return None
    i = rng.choice(pos)
    ch = value[i]
    pool = "0123456789" if ch.isdigit() else "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    if kind == "look_alike":
        cand = [j for j in pos if value[j].upper() in _LOOKALIKE]
        if not cand:
            return None
        j = rng.choice(cand)
        return value[:j] + _LOOKALIKE[value[j].upper()] + value[j + 1 :]
    if kind == "same_class_substitution":
        new = rng.choice([c for c in pool if c != ch.upper()])
        return value[:i] + (new.lower() if ch.islower() else new) + value[i + 1 :]
    if kind == "drop_char":
        return value[:i] + value[i + 1 :]
    if kind == "insert_char":
        return value[:i] + rng.choice(pool) + value[i:]
    if kind == "swap_adjacent":
        j = i + 1
        if j >= len(value) or not value[j].isalnum() or value[j] == ch:
            return None
        return value[:i] + value[j] + ch + value[j + 2 :]
    raise ValueError(kind)


def validator_injection(corpus_gold: list[dict[str, Any]]) -> dict[str, Any]:
    """SYNTHETIC: catch rate of each flag on gold values with one injected reading error."""
    rng = random.Random(SEED)
    groups = {
        "currency": ("currency",),
        "airport": ("origin_airport", "destination_airport"),
        "awb": ("awb_number", "mawb"),
        "hawb": ("hawb",),
    }
    kinds = ("look_alike", "same_class_substitution", "drop_char", "insert_char", "swap_adjacent")
    res: dict[str, dict[str, list[int]]] = {g: {k: [0, 0] for k in kinds} for g in groups}
    for g in corpus_gold:
        for f, v in g["header"].items():
            for gname, fields in groups.items():
                if f not in fields or v is None or not str(v).strip():
                    continue
                for k in kinds:
                    m = _mutate(str(v), k, rng)
                    if m is None or m == str(v):
                        continue
                    res[gname][k][0] += 1
                    res[gname][k][1] += bool(validate_value(f, m))
    return {g: {k: {"n": a, "flagged": b} for k, (a, b) in d.items()} for g, d in res.items()}


