def test_cost_train_is_the_step_sum_and_counts_interrupted_sessions() -> None:
    t = ri.cost_train_from_run(_STEPS, _TRAIN_SESSIONS, _train_status())
    assert t["step_seconds_sum"] == 60.0 and t["s_per_step"] == 20.0
    assert t["hours"] == pytest.approx(60 / 3600)
    assert (t["sessions"], t["interrupted_sessions"]) == (3, 2)
    assert t["peak_vram_gib"] == 11.0 and t["precision"] == "bf16"
    with pytest.raises(br.ReportError, match="steps are not exactly"):
        ri.cost_train_from_run(_STEPS[:2], _TRAIN_SESSIONS, _train_status())
    with pytest.raises(br.ReportError, match="steps are not exactly"):
        ri.cost_train_from_run([*_STEPS, _STEPS[0]], _TRAIN_SESSIONS, _train_status())
    with pytest.raises(br.ReportError, match="complete"):
        ri.cost_train_from_run(_STEPS, _TRAIN_SESSIONS, {**_train_status(), "state": "running"})
    with pytest.raises(br.ReportError, match="exit 0"):
        ri.cost_train_from_run(_STEPS, _TRAIN_SESSIONS[:2], _train_status())


