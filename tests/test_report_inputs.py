def _est(p: float, lo: float, hi: float) -> dict[str, float]:
    return {"point": p, "lo": lo, "hi": hi}


def _tau_row(pop: str, t: float, prec: Any, cov: float, n: int = 100) -> dict[str, Any]:
    nan = float("nan")
    return {
        "population": pop,
        "target": t,
        "slice": "all",
        "scheme": "nested",
        "n": n,
        "precision_accepted": prec if prec is not None else _est(nan, nan, nan),
        "accepted_share": _est(cov, cov - 0.01, cov + 0.01),
    }


def _v2() -> dict[str, Any]:
    spec = {
        "header": (_est(0.99, 0.98, 1.0), 1.0),  # attained
        "supplier_part_number": (_est(0.979, 0.96, 0.99), 0.74),  # near-miss at 0.98
        "customer_part_number": (_est(0.0, 0.0, 0.0), 0.03),  # coverage under the minimum
        "purchase_order": (None, 0.0),  # nothing auto-accepted
        "quantity": (_est(0.72, 0.47, 0.92), 0.013),
        "all_per_type_tau": (_est(0.90, 0.88, 0.92), 0.4),  # CI misses the target
    }
    tau = [_tau_row(p, t, *spec[p]) for p in spec for t in (0.95, 0.98, 0.99)]
    doc = [_tau_row("doc", t, _est(0.9, 0.8, 0.97), 0.08, n=500) for t in (0.95, 0.98)]
    # one ECE per group: 0.01, 0.02, ... in this order (all_per_type_tau lives under all_emitted)
    ece_groups = [*(p for p in spec if p != "all_per_type_tau"), "doc", "all_emitted"]
    return {
        "slice_docs": {"all": 500, "dev": 100},
        "tau": tau,
        "doc_level": doc,
        "doc_attainability": {"0.95": {"attained": False}, "0.98": {"attained": False}},
        "provenance": {"shapes_equal": {"0": True, "1": True, "2": False}},  # JSON str keys
        "calibration": [
            {"slice": "all", "group": g, "ece_width15": 0.01 * (i + 1)}
            for i, g in enumerate(ece_groups)
        ],
    }


