def test_measured_cost_end_to_end_leaves_only_the_price_pending(tmp_path: Path) -> None:
    run = tmp_path / "run"
    run.mkdir()
    trace = [{"pages": [{"meta": {"latency_s": s, "peak_vram_bytes": 2**30}}]} for s in (1, 2, 3)]
    _write(run / "trace.jsonl", "\n".join(json.dumps(x) for x in trace))
    _write(run / "metrics.json", json.dumps({"n_docs": 2, "n_pages": 3}))
    _write(run / "sessions.json", json.dumps([{"seconds": 30.0}]))
    _write(run / "manifest.json", json.dumps({"batch_size": 8}))
    tr = tmp_path / "train"
    tr.mkdir()
    _write(tr / "metrics.jsonl", "\n".join(json.dumps(s) for s in _STEPS))
    _write(tr / "sessions.json", json.dumps(_TRAIN_SESSIONS))
    _write(tr / "train_status.json", json.dumps(_train_status()))
    oof = tmp_path / "oof"
    oof.mkdir()
    _write(oof / "sessions.json", json.dumps([{"seconds": 360.0}]))
    _write(oof / "manifest.json", json.dumps({"oof": {"merge": {"load_and_merge_s": 5.0}}}))
    _write(oof / "metrics.json", json.dumps({"n_pages": 12}))
    out = tmp_path / "out"
    args = [
        "--out-dir", str(out),
        "--run-dir", str(run),
        "--submission-manifest", str(_write(tmp_path / "v0.json", json.dumps(_v0()))),
        "--ocr-timing", str(_write(tmp_path / "ocr.json", json.dumps(_ocr()))),
        "--train-dir", str(tr),
        "--oof-dir", str(oof),
        "--res-sweep-md", str(_write(tmp_path / "res.md", RES_MD)),
    ]  # fmt: skip
    assert ri.main(args) == 0
    man = json.loads((out / "inputs.json").read_text("utf-8"))
    assert man["sources"]["cost"]["status"] == "unverified"  # measured, not yet re-computed
    assert man["sources"]["cost_est"]["status"] == "estimated"
    text, left = br.fill(
        br.TEMPLATE.read_text(encoding="utf-8"), br.load_manifest(out / "inputs.json")
    )
    assert [p for p in left if p.startswith(("cost.", "latency."))] == []
    assert {p for p in left if p.startswith("cost_est.")} == {
        "cost_est.hourly_usd",
        "cost_est.price_source",
        "cost_est.usd_per_1000_docs",
    }
    assert "ESTIMATE, UNVERIFIED" in text and "UNMEASURED" in text
    # a price supplied by hand fills the estimate namespace and computes USD per 1,000 docs
    price = _write(tmp_path / "price.json", json.dumps({"hourly_usd": 0.5, "price_source": "x"}))
    assert ri.main([*args, "--cost", str(price)]) == 0
    est = json.loads((out / "cost_est.json").read_text("utf-8"))
    assert est["usd_per_1000_docs"] == pytest.approx(2.0 * 1.5 * 1000 / 3600 * 0.5)
    # a given path that does not exist is an error, not a silent skip
    assert ri.main([*args[:-2], "--res-sweep-md", str(tmp_path / "nope.md")]) == 1


