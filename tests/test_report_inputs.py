def _write(p: Path, text: str) -> Path:
    p.write_text(text, encoding="utf-8")
    return p


def test_end_to_end_resolves_the_new_keys_and_only_expected_pending(tmp_path: Path) -> None:
    run = tmp_path / "run"
    run.mkdir()
    trace = [{"pages": [{"meta": {"latency_s": s, "peak_vram_bytes": 2**30}}]} for s in (1, 2, 3)]
    _write(run / "trace.jsonl", "\n".join(json.dumps(x) for x in trace))
    _write(run / "metrics.json", json.dumps({"n_docs": 2, "n_pages": 3}))
    v2d, v1d = tmp_path / "v2", tmp_path / "v1"
    v2d.mkdir()
    v1d.mkdir()
    _write(v2d / "calibration_v2.json", json.dumps(_v2()))
    _write(v1d / "calibration.json", json.dumps(_v1()))
    out = tmp_path / "out"
    rc = ri.main(
        [
            "--out-dir", str(out),
            "--run-dir", str(run),
            "--calibration-v2-dir", str(v2d),
            "--calibration-dir", str(v1d),
            "--ablation-json", str(_write(tmp_path / "abl.json", json.dumps(_ablation()))),
            "--v1-replay-md", str(_write(tmp_path / "v1.md", REPLAY_MD)),
            "--rule-gate-md", str(_write(tmp_path / "gate.md", GATE_MD)),
            "--layout-md", str(_write(tmp_path / "lay.md", LAYOUT_MD)),
            "--row-errors-md", str(_write(tmp_path / "re.md", ROW_ERRORS_MD)),
            "--value", "report_date=2000-01-01",
        ]
    )  # fmt: skip
    assert rc == 0
    man = json.loads((out / "inputs.json").read_text("utf-8"))
    assert set(man["sources"]) == {
        "ablation", "failure", "clusters", "calibration", "rules", "cost"
    }  # fmt: skip
    assert {s["status"] for s in man["sources"].values()} <= {"unverified", "estimated"}
    ctx = br.load_manifest(out / "inputs.json")
    text, left = br.fill(br.TEMPLATE.read_text(encoding="utf-8"), ctx)
    assert "R3 disclosure" in text
    pending = set(left)
    # nothing the converters claim to produce may stay pending
    for prefix in (
        "rules.",
        "failure.",
        "ablation.",
        "calibration.types",
        "latency.",
        "cost.pages",
    ):
        assert not [p for p in pending if p.startswith(prefix)], pending
    for key in ("row_null_policy", "false_fill", "dev_docs", "n_docs", "min_coverage"):
        assert f"calibration.{key}" not in pending
    # no model was ever run on the synthetic-redaction pages: produced by nothing, by design
    assert "calibration.synthetic_redaction.null_rate" in pending
    assert "clusters.predicted_review_rate" in pending
    assert "values.model_state" in pending


